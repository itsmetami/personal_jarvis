function replyJson(res: import('node:http').ServerResponse, status: number, body: unknown) {
  res.statusCode = status
  res.setHeader('content-type', 'application/json; charset=utf-8')
  res.setHeader('cache-control', 'no-store')
  res.setHeader('x-content-type-options', 'nosniff')
  res.end(JSON.stringify(body))
}

function launch(executable: string, args: string[] = []): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, {
      detached: true,
      stdio: 'ignore',
      // These are interactive desktop apps. Hiding the launcher process also
      // hides some Windows packaged apps when they are activated through it.
      windowsHide: false,
    })
    child.once('error', reject)
    child.once('spawn', () => {
      child.unref()
      resolve()
    })
  })
}

function readBody(req: import('node:http').IncomingMessage): Promise<Record<string, unknown>> {
  return new Promise((resolve, reject) => {
    let body = ''
    req.setEncoding('utf8')
    req.on('data', (chunk: string) => {
      body += chunk
      if (body.length > 4096) reject(new Error('Request is too large.'))
    })
    req.on('end', () => {
      try {
        const value = body ? JSON.parse(body) : {}
        if (!value || typeof value !== 'object' || Array.isArray(value)) {
          throw new Error('Expected a JSON object.')
        }
        resolve(value)
      } catch (error) {
        reject(error)
      }
    })
    req.on('error', reject)
  })
}

function desktopApi() {
  return {
    name: 'jarvis-local-desktop-actions',
    configureServer(server: import('vite').ViteDevServer) {
      server.middlewares.use((req, res, next) => {
        const requestUrl = new URL(req.url ?? '/', 'http://localhost')
        if (!requestUrl.pathname.startsWith('/desktop/')) return next()

        void (async () => {
          const origin = req.headers.origin
          let originUrl: URL
          try {
            originUrl = new URL(origin ?? '')
          } catch {
            replyJson(res, 403, { error: 'A local JARVIS page is required.' })
            return
          }
          const originPort = Number(originUrl.port)
          if (
            originUrl.protocol !== 'http:' ||
            !['localhost', '127.0.0.1'].includes(originUrl.hostname) ||
            originPort < 5173 || originPort > 5199 ||
            !['localhost', '127.0.0.1'].includes((req.headers.host ?? '').split(':')[0])
          ) {
            replyJson(res, 403, { error: 'Desktop actions are limited to this local JARVIS page.' })
            return
          }
          const route = requestUrl.pathname.slice('/desktop/'.length)
          if (route === 'profile' && req.method === 'POST') {
            const profilePath = path.resolve(process.cwd(), 'personalization', 'profile.md')
            let profile = ''
            try {
              profile = readFileSync(profilePath, 'utf8').slice(0, 12000)
            } catch {
              // A missing private profile is an ordinary fresh-install state.
            }
            replyJson(res, 200, { profile })
            return
          }
          if (req.method !== 'POST') {
            replyJson(res, 405, { error: 'Use POST for local desktop actions.' })
            return
          }

          try {
            const input = await readBody(req)
            if (route === 'time') {
              const now = new Date()
              const formatted = new Intl.DateTimeFormat(undefined, {
                dateStyle: 'full',
                timeStyle: 'short',
              }).format(now)
              replyJson(res, 200, {
                result: formatted,
                timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
              })
              return
            }

            if (route === 'open-app') {
              const app = typeof input.app === 'string' ? input.app.toLowerCase() : ''
              const getTarget = DESKTOP_APPS[app]
              if (!getTarget) {
                replyJson(res, 400, { error: 'That app is not on the allowed list.' })
                return
              }
              const target = getTarget()
              if (!target) {
                replyJson(res, 404, { error: `I could not find ${app} installed in its usual location.` })
                return
              }
              await launch(target.executable, target.args)
              // spawn() only confirms that the launcher process started. It does
              // not confirm Windows activated the app in the user's desktop
              // session (notably for Store apps via Explorer).
              replyJson(res, 200, {
                result: `I sent Windows a request to open ${app}, but I cannot confirm it appeared on your desktop. If it did not open, restart JARVIS with Start-JARVIS.bat from your signed-in Windows desktop and use the localhost address printed in that window.`,
              })
              return
            }

            if (route === 'open-folder') {
              const folder = typeof input.folder === 'string' ? input.folder.toLowerCase() : ''
              const name = FOLDER_NAMES[folder]
              if (!name) {
                replyJson(res, 400, { error: 'That folder is not on the allowed list.' })
                return
              }
              const home = process.env.USERPROFILE || os.homedir()
              const oneDrive = process.env.OneDrive
              const candidates = [
                ...(oneDrive ? [path.join(oneDrive, name)] : []),
                path.join(home, name),
              ]
              const target = candidates.find(existsSync)
              if (!target) {
                replyJson(res, 404, { error: `The ${folder} folder was not found.` })
                return
              }
              await launch('explorer.exe', [target])
              replyJson(res, 200, { result: `Opened ${folder}.` })
              return
            }

            if (route === 'open-url') {
              if (typeof input.url !== 'string' || input.url.length > 2048) {
                replyJson(res, 400, { error: 'Give me a web address to open.' })
                return
              }
              const target = new URL(input.url)
              if (!['http:', 'https:'].includes(target.protocol) || !target.hostname || target.username || target.password) {
                replyJson(res, 400, { error: 'Only ordinary HTTP or HTTPS web addresses can be opened.' })
                return
              }
              await launch('explorer.exe', [target.href])
              replyJson(res, 200, { result: `Opened ${target.hostname}.` })
              return
            }

            replyJson(res, 404, { error: 'That desktop action is not available.' })
          } catch (error) {
            replyJson(res, 500, {
              error: error instanceof Error ? error.message : 'The desktop action failed.',
            })
          }
        })()
      })
    },
  }
}

