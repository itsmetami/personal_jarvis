type DesktopTarget = { executable: string; args?: string[] }
const appsFolder = (appId: string): DesktopTarget => ({
  executable: 'explorer.exe',
  args: [`shell:AppsFolder\\${appId}`],
})
function installedPath(candidates: Array<string | undefined>): DesktopTarget | null {
  const executable = candidates.find((candidate) => candidate && existsSync(candidate))
  return executable ? { executable } : null
}
function robloxPath(executable: 'RobloxPlayerBeta.exe' | 'RobloxStudioBeta.exe'): DesktopTarget | null {
  const versions = path.join(process.env.LOCALAPPDATA || '', 'Roblox', 'Versions')
  if (!existsSync(versions)) return null
  try {
    const candidates = readdirSync(versions, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => path.join(versions, entry.name, executable))
    return installedPath(candidates)
  } catch {
    return null
  }
}
